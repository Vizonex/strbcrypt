from dataclasses import dataclass

import bcrypt


@dataclass(slots=True, frozen=True)
class StrBcrypt:
    """An object defining the encoding to provide to each password,
    the encoding errors to provide and the number of rounds and prefix
    of each given hash."""

    encoding: str = "utf-8"
    errors: str = "strict"
    rounds: int = 10
    prefix: bytes = b"2b"

    def decode(self, input_bytes: bytes) -> str:
        """
        Decodes bytes to string based on the encoding provided and the error
        kind given.

        :param input_str: the bytes to decode a string

        """
        return input_bytes.decode(self.encoding, self.errors)

    def encode(self, input_str: str) -> bytes:
        """
        Encodes a string based on the encoding provided and the error
        kind given.

        :param input_str: the string to encode to bytes
        """
        return input_str.encode(self.encoding, self.errors)

    def gensalt(self) -> bytes:
        """Generates a salt based on the previously passed number
        of rounds and prefix."""
        return bcrypt.gensalt(self.rounds, self.prefix)

    def hashpw(self, password: str, salt: bytes | None = None) -> str:
        """Hashes a single password.

        :param password: the password to input
        :param salt: a default salt to provide otherwise
            it will be generated by default.

        :returns: a hashed password as a string object.
        """
        return self.decode(bcrypt.hashpw(self.encode(password), salt or self.gensalt()))

    def checkpw(self, password: str, hashed_pw: str) -> bool:
        """Validates a single password.

        :param password: the password to validate.
        :param hashed_pw: the hashed password to verify against.

        :returns: a boolean signaling if password is successful.
        """
        return bcrypt.checkpw(self.encode(password), self.encode(hashed_pw))
