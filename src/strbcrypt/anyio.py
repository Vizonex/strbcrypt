from anyio.to_thread import run_sync

from . import core


class AsyncStrBcrypt:
    """Makes bcrypt class asynchronous"""

    __slots__ = ("_sync",)

    def __init__(
        self,
        encoding: str = "utf-8",
        errors: str = "ignore",
        rounds: int = 10,
        prefix: bytes = b"2b",
    ) -> None:
        """
        :param encoding: The encoding to convert bytes and strings using.
        :param errors: The error handler to use.
        :param rounds: Number of rounds to use with each given generated salt.
        :param prefix: The prefix that should be utilized with each salt generated.
        """
        self._sync = core.StrBcrypt(encoding, errors, rounds, prefix)

    @property
    def encoding(self) -> str:
        "The encoding to convert bytes and strings using."
        return self._sync.encoding

    @property
    def errors(self) -> str:
        """The error handler to use."""
        return self._sync.errors

    @property
    def rounds(self) -> int:
        """Number of rounds to use with each given generated salt."""
        return self._sync.rounds

    @property
    def prefix(self) -> bytes:
        "The prefix that should be utilized with each salt generated."
        return self._sync.prefix

    async def hashpw(self, password: str, salt: bytes | None = None) -> str:
        """Hashes a single password

        :param password: the password to input
        :param salt: a default salt to provide otherwise
            it will be generated by default.

        :returns: a hashed password as a string object.
        """
        return await run_sync(self._sync.hashpw, password, salt)

    async def checkpw(self, password: str, hashed_pw: str) -> bool:
        """Validates a single password.

        :param password: the password to validate.
        :param hashed_pw: the hashed password to verify against.

        :returns: a boolean signaling if password is successful.
        """
        return await run_sync(self._sync.checkpw, password, hashed_pw)


__all__ = ("AsyncStrBcrypt",)
